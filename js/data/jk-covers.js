window.KLIPER_GET_JK_COVER = function (building) {
  if (!building) return '';

  var developer = building.developer || '';
  var name = building.name || building.title || '';
  var developerKey = developer + '|' + name;

  if (window.KLIPER_JK_COVERS_BY_DEVELOPER && window.KLIPER_JK_COVERS_BY_DEVELOPER[developerKey]) {
    return window.KLIPER_JK_COVERS_BY_DEVELOPER[developerKey];
  }

  if (window.KLIPER_JK_COVERS && window.KLIPER_JK_COVERS[name]) {
    return window.KLIPER_JK_COVERS[name];
  }

  return '';
};
